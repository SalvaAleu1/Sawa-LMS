-- Controlled provisioning and subscription operations. Server-only service_role may call these.
create or replace function public.platform_approve_partner(
 p_application_id uuid, p_actor uuid, p_slug text, p_plan_code text, p_period text, p_invite_token_hash text
) returns table(institution_id uuid, invite_id uuid, invite_token_hash text)
language plpgsql security definer set search_path=public
as $$
declare a public.partner_applications%rowtype; pl public.subscription_plans%rowtype; i uuid; sub uuid; token_hash text;
begin
 if not exists(select 1 from public.platform_memberships where user_id=p_actor and role in ('platform_owner','platform_admin')) then
  raise exception 'platform_operator_required' using errcode='42501';
 end if;
 select * into a from public.partner_applications where id=p_application_id for update;
 if not found or a.status not in ('pending_review','under_review') then raise exception 'application_not_reviewable' using errcode='22023'; end if;
 if p_period not in ('monthly','annual') then raise exception 'invalid_billing_period' using errcode='22023'; end if;
 select * into pl from public.subscription_plans where code=p_plan_code and is_active;
 if not found then raise exception 'active_plan_not_found' using errcode='22023'; end if;
 if exists(select 1 from public.institutions where slug=p_slug) then raise exception 'institution_slug_exists' using errcode='23505'; end if;
 insert into public.institutions(slug,legal_name,display_name,institution_type,country_code,status,approved_by,approved_at)
 values(lower(p_slug),a.legal_name,a.display_name,a.institution_type,a.country_code,'active',p_actor,now()) returning id into i;
 insert into public.institution_subscriptions(institution_id,plan_id,status,billing_period,period_start,period_end,grace_end,created_by)
 values(i,pl.id,'pending_payment',p_period,current_date,
   case when p_period='annual' then (current_date + interval '1 year')::date else (current_date + interval '1 month')::date end,
   case when p_period='annual' then (current_date + interval '1 year 7 days')::date else (current_date + interval '1 month 7 days')::date end,p_actor)
 returning id into sub;
 -- Token is generated by the Worker. Only its SHA-256 hash is stored.
 token_hash := p_invite_token_hash;
 if token_hash is null or length(token_hash)<32 then raise exception 'invite_token_hash_required' using errcode='22023'; end if;
 insert into public.first_admin_invites(institution_id,email,token_hash,approved_by,expires_at)
 values(i,lower(a.contact_email),token_hash,p_actor,now()+interval '72 hours') returning id into invite_id;
 update public.partner_applications set status='approved',reviewed_by=p_actor,reviewed_at=now(),created_institution_id=i where id=a.id;
 insert into public.audit_logs(actor_user_id,institution_id,action,target_type,target_id,metadata)
 values(p_actor,i,'partner_approved','partner_application',a.id::text,jsonb_build_object('subscription_id',sub,'plan_code',p_plan_code,'period',p_period,'invite_id',invite_id));
 institution_id := i; invite_token_hash := token_hash; return next;
end $$;
revoke all on function public.platform_approve_partner(uuid,uuid,text,text,text,text) from public, anon, authenticated;
grant execute on function public.platform_approve_partner(uuid,uuid,text,text,text,text) to service_role;

create or replace function public.platform_record_cash_receipt(
 p_actor uuid,p_institution uuid,p_subscription uuid,p_amount numeric,p_currency char(3),p_received_on date,
 p_period text,p_covered_from date,p_covered_until date,p_exchange_rate numeric,p_reference text,p_notes text,p_confirm boolean
) returns bigint language plpgsql security definer set search_path=public
as $$
declare r public.cash_receipts%rowtype; s public.institution_subscriptions%rowtype;
begin
 if not exists(select 1 from public.platform_memberships where user_id=p_actor and role in ('platform_owner','platform_admin')) then
  raise exception 'platform_operator_required' using errcode='42501';
 end if;
 if p_amount<=0 or p_period not in ('monthly','annual') or p_covered_until<p_covered_from then raise exception 'invalid_receipt' using errcode='22023'; end if;
 select * into s from public.institution_subscriptions where id=p_subscription and institution_id=p_institution for update;
 if not found then raise exception 'subscription_not_found' using errcode='22023'; end if;
 insert into public.cash_receipts(institution_id,subscription_id,amount,currency,received_on,billing_period,covered_from,covered_until,exchange_rate,payment_reference,notes,recorded_by,confirmed_at,confirmed_by)
 values(p_institution,p_subscription,p_amount,p_currency,p_received_on,p_period,p_covered_from,p_covered_until,p_exchange_rate,p_reference,p_notes,p_actor,
 case when p_confirm then now() else null end,case when p_confirm then p_actor else null end)
 returning * into r;
 if p_confirm then
   update public.institution_subscriptions set status='active',period_start=p_covered_from,period_end=p_covered_until,
     grace_end=p_covered_until+7,owner_decision_required=false,updated_at=now() where id=p_subscription;
 end if;
 insert into public.audit_logs(actor_user_id,institution_id,action,target_type,target_id,metadata)
 values(p_actor,p_institution,case when p_confirm then 'cash_receipt_confirmed' else 'cash_receipt_recorded' end,'cash_receipt',r.id::text,
 jsonb_build_object('receipt_number',r.receipt_number,'amount',p_amount,'currency',p_currency,'confirmed',p_confirm));
 return r.receipt_number;
end $$;
revoke all on function public.platform_record_cash_receipt(uuid,uuid,uuid,numeric,char,date,text,date,date,numeric,text,text,boolean) from public, anon, authenticated;
grant execute on function public.platform_record_cash_receipt(uuid,uuid,uuid,numeric,char,date,text,date,date,numeric,text,text,boolean) to service_role;

